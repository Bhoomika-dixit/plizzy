"use client";

/** Lets a player select which manifest-backed game the stable runtime should render. */
import { useState } from "react";
import { manifest as fishManifest } from "../agent-response/manifest";
import { manifest as sudokuManifest } from "../agent-response-sudoku/manifest";
import { GameRuntime } from "../runtime/game-runtime";
import styles from "./game-picker.module.css";

const games = [
  { id: "fish", label: "Fish Tap", manifest: fishManifest },
  { id: "sudoku", label: "Sudoku Twist", manifest: sudokuManifest },
] as const;

/**
 * What it does: Switches the active manifest without changing the shared route or runtime.
 * Can be generated by AI?: No.
 */
export function GamePicker() {
  const [selectedId, setSelectedId] = useState<(typeof games)[number]["id"]>("fish");
  const selectedGame = games.find((game) => game.id === selectedId) ?? games[0];

  return (
    <>
      <nav className={styles.picker} aria-label="Choose a game">
        {games.map((game) => <button key={game.id} type="button" aria-pressed={game.id === selectedId} onClick={() => setSelectedId(game.id)}>{game.label}</button>)}
      </nav>
      <GameRuntime key={selectedGame.id} manifest={selectedGame.manifest} />
    </>
  );
}
