"use client";

/** Implements the reusable renderer, rules, and animation loop for every falling-tap game. */
import Image from "next/image";
import { useEffect, useReducer, useRef } from "react";
import type { FallingTapManifest } from "./game-manifest";
import styles from "./falling-tap-runtime.module.css";

type Target = { id: number; x: number; y: number; spawnedAt: number };
type Phase = "intro" | "playing" | "finished";
type State = {
  phase: Phase;
  startedAt: number | null;
  lastSpawnedAt: number | null;
  nextTargetId: number;
  score: number;
  caught: number;
  missed: number;
  timeLeftMs: number;
  targets: Target[];
};
type Event =
  | { type: "START"; now: number }
  | { type: "FRAME"; now: number; arenaWidth: number }
  | { type: "TAP_TARGET"; targetId: number }
  | { type: "REPLAY" };

const targetSize = 64;
const arenaHeight = 420;
const groundHeight = 36;

/**
 * What it does: Creates an empty state from the supplied game's duration rule.
 * Can be generated by AI?: No.
 */
function initialState(manifest: FallingTapManifest): State {
  return {
    phase: "intro",
    startedAt: null,
    lastSpawnedAt: null,
    nextTargetId: 1,
    score: 0,
    caught: 0,
    missed: 0,
    timeLeftMs: manifest.rules.roundDurationMs,
    targets: [],
  };
}

/**
 * What it does: Applies a player action or animation-frame update to the shared falling-tap rules.
 * Can be generated by AI?: No.
 */
function reduce(manifest: FallingTapManifest, state: State, event: Event): State {
  if (event.type === "REPLAY") return initialState(manifest);

  if (event.type === "START") {
    return {
      ...initialState(manifest),
      phase: "playing",
      startedAt: event.now,
      lastSpawnedAt: event.now - manifest.rules.targetSpawnIntervalMs,
    };
  }

  if (event.type === "TAP_TARGET") {
    if (state.phase !== "playing" || !state.targets.some((target) => target.id === event.targetId)) return state;
    return {
      ...state,
      score: state.score + manifest.rules.pointsPerTarget,
      caught: state.caught + 1,
      targets: state.targets.filter((target) => target.id !== event.targetId),
    };
  }

  if (state.phase !== "playing" || state.startedAt === null) return state;

  const timeLeftMs = Math.max(0, manifest.rules.roundDurationMs - (event.now - state.startedAt));
  if (timeLeftMs === 0) return { ...state, phase: "finished", timeLeftMs: 0, targets: [] };

  let newlyMissed = 0;
  const maximumY = arenaHeight - groundHeight - targetSize;
  const activeTargets = state.targets.flatMap((target) => {
    const progress = (event.now - target.spawnedAt) / manifest.rules.targetFallDurationMs;
    if (progress >= 1) {
      newlyMissed += 1;
      return [];
    }
    return [{ ...target, y: Math.round(progress * maximumY) }];
  });

  const shouldSpawn = state.lastSpawnedAt === null || event.now - state.lastSpawnedAt >= manifest.rules.targetSpawnIntervalMs;
  const spawnedTarget = shouldSpawn
    ? { id: state.nextTargetId, x: Math.round(Math.random() * Math.max(0, event.arenaWidth - targetSize)), y: 0, spawnedAt: event.now }
    : null;

  return {
    ...state,
    timeLeftMs,
    missed: state.missed + newlyMissed,
    targets: spawnedTarget ? [...activeTargets, spawnedTarget] : activeTargets,
    lastSpawnedAt: spawnedTarget ? event.now : state.lastSpawnedAt,
    nextTargetId: spawnedTarget ? state.nextTargetId + 1 : state.nextTargetId,
  };
}

/**
 * What it does: Renders any falling-tap manifest and connects it to the shared engine.
 * Can be generated by AI?: No.
 */
export function FallingTapRuntime({ manifest }: { manifest: FallingTapManifest }) {
  const arenaRef = useRef<HTMLDivElement>(null);
  const [state, dispatch] = useReducer(
    (currentState: State, event: Event) => reduce(manifest, currentState, event),
    manifest,
    initialState,
  );

  useEffect(() => {
    if (state.phase !== "playing") return;
    let frameId = 0;
    const tick = (now: number) => {
      dispatch({ type: "FRAME", now, arenaWidth: arenaRef.current?.clientWidth ?? 720 });
      frameId = requestAnimationFrame(tick);
    };
    frameId = requestAnimationFrame(tick);
    return () => cancelAnimationFrame(frameId);
  }, [state.phase]);

  const timeLeft = Math.ceil(state.timeLeftMs / 1000);
  const attempts = state.caught + state.missed;
  const accuracy = attempts ? Math.round((state.caught / attempts) * 100) : 0;

  return (
    <section className={styles.game} style={{ background: manifest.theme.pageBackground, color: manifest.theme.textColor }} aria-label={manifest.metadata.title}>
      <div className={styles.hud}>
        <Stat label="Time left" value={`${timeLeft}s`} />
        <Stat label="Score" value={state.score} />
        <Stat label="Missed" value={state.missed} />
      </div>
      <div ref={arenaRef} className={styles.arena} style={{ background: manifest.theme.arenaBackground }}>
        <div className={styles.ground} style={{ background: manifest.theme.groundColor }} />
        {state.targets.map((target) => (
          <button key={target.id} type="button" className={styles.target} style={{ transform: `translate(${target.x}px, ${target.y}px)` }} onPointerDown={() => dispatch({ type: "TAP_TARGET", targetId: target.id })} aria-label="Catch target">
            <Image src={manifest.assets.target.src} alt={manifest.assets.target.alt} width={targetSize} height={targetSize} draggable={false} />
          </button>
        ))}
        {state.phase !== "playing" && (
          <div className={styles.overlay}>
            {state.phase === "intro" ? <><h1>{manifest.metadata.title}</h1><p>{manifest.metadata.instructions}</p><button type="button" style={{ background: manifest.theme.accentColor }} onClick={() => dispatch({ type: "START", now: performance.now() })}>Start game</button></> : <><h1>Time is up</h1><p className={styles.finalScore}>Final score: {state.score}</p><div className={styles.results}><Stat label="Caught" value={state.caught} /><Stat label="Missed" value={state.missed} /><Stat label="Accuracy" value={`${accuracy}%`} /></div><button type="button" style={{ background: manifest.theme.accentColor }} onClick={() => { dispatch({ type: "REPLAY" }); requestAnimationFrame(() => dispatch({ type: "START", now: performance.now() })); }}>Play again</button></>}
          </div>
        )}
      </div>
    </section>
  );
}

/**
 * What it does: Renders one numeric metric in the shared game HUD or result view.
 * Can be generated by AI?: No.
 */
function Stat({ label, value }: { label: string; value: string | number }) {
  return <div className={styles.stat}><span>{label}</span><strong>{value}</strong></div>;
}
