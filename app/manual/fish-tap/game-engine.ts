/** Applies Fish Tap's deterministic gameplay rules without rendering any user interface. */
import { fishTapGameSpec } from "./game-spec";
import type {
  FishEntity,
  FishTapEvent,
  FishTapState,
} from "./game-types";

const { arena, round, scoring } = fishTapGameSpec;
const fishWidth = 64;
const fishHeight = 64;

export const initialFishTapState: FishTapState = {
  phase: "intro",
  startedAt: null,
  lastSpawnedAt: null,
  nextFishId: 1,
  timeLeftMs: round.durationMs,
  score: 0,
  caught: 0,
  missed: 0,
  fish: [],
};

/**
 * What it does: Creates one falling fish at a random valid horizontal position.
 * Can be generated by AI?: Yes.
 */
function spawnFish(state: FishTapState, arenaWidth: number, now: number): FishEntity {
  const maxX = Math.max(0, arenaWidth - fishWidth);

  return {
    id: `fish_${state.nextFishId}`,
    x: Math.round(Math.random() * maxX),
    y: 0,
    spawnedAt: now,
    status: "falling",
  };
}

/**
 * What it does: Converts one game event into the next valid Fish Tap game state.
 * Can be generated by AI?: Yes.
 */
export function reduceFishTapGame(
  state: FishTapState,
  event: FishTapEvent,
): FishTapState {
  if (event.type === "REPLAY") {
    return initialFishTapState;
  }

  if (event.type === "START") {
    return {
      ...initialFishTapState,
      phase: "playing",
      startedAt: event.now,
      lastSpawnedAt: event.now - round.spawnIntervalMs,
    };
  }

  if (event.type === "TAP_FISH") {
    if (state.phase !== "playing") return state;

    const target = state.fish.find(
      (fish) => fish.id === event.fishId && fish.status === "falling",
    );

    if (!target) return state;

    return {
      ...state,
      score: state.score + scoring.pointsPerFish,
      caught: state.caught + 1,
      fish: state.fish.filter((fish) => fish.id !== event.fishId),
    };
  }

  if (state.phase !== "playing" || state.startedAt === null) return state;

  const elapsedMs = event.now - state.startedAt;
  const timeLeftMs = Math.max(0, round.durationMs - elapsedMs);

  if (timeLeftMs === 0) {
    return {
      ...state,
      phase: "finished",
      timeLeftMs: 0,
      fish: [],
    };
  }

  let newlyMissed = 0;
  const maxY = arena.height - arena.groundHeight - fishHeight;

  const fallingFish = state.fish.flatMap((fish) => {
    const progress = (event.now - fish.spawnedAt) / round.fishFallDurationMs;

    if (progress >= 1) {
      newlyMissed += 1;
      return [];
    }

    return [
      {
        ...fish,
        y: Math.round(progress * maxY),
      },
    ];
  });

  const shouldSpawn =
    state.lastSpawnedAt === null ||
    event.now - state.lastSpawnedAt >= round.spawnIntervalMs;

  const spawnedFish = shouldSpawn
    ? spawnFish(state, event.arenaWidth, event.now)
    : null;

  return {
    ...state,
    timeLeftMs,
    missed: state.missed + newlyMissed,
    fish: spawnedFish ? [...fallingFish, spawnedFish] : fallingFish,
    lastSpawnedAt: spawnedFish ? event.now : state.lastSpawnedAt,
    nextFishId: spawnedFish ? state.nextFishId + 1 : state.nextFishId,
  };
}
